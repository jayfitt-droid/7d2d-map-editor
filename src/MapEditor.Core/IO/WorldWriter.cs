using MapEditor.Core.Model;

namespace MapEditor.Core.IO;

public sealed class WorldWriteOptions
{
    /// <summary>Allow writing into a folder that already has files (derived caches are deleted).</summary>
    public bool Overwrite { get; init; }

    /// <summary>A main.ttw to use when the world has none (copy one from a world made by the same game version).</summary>
    public string? LevelTemplatePath { get; init; }
}

/// <summary>Writes a <see cref="World"/> as a game world folder the game can load and process.</summary>
public static class WorldWriter
{
    public static void Write(World world, string folder, WorldWriteOptions? options = null)
    {
        options ??= new WorldWriteOptions();
        if (Directory.Exists(folder) && Directory.EnumerateFileSystemEntries(folder).Any())
        {
            if (!options.Overwrite) throw new IOException($"'{folder}' is not empty.");
            // Stale caches would make the game skip reprocessing (it checks checksums.txt).
            foreach (var file in Directory.EnumerateFiles(folder))
                if (WorldFiles.IsDerived(Path.GetFileName(file))) File.Delete(file);
        }
        Directory.CreateDirectory(folder);
        string P(string file) => Path.Combine(folder, file);

        HeightRaw.Write(P(WorldFiles.Height), world.Height);
        WorldXml.WriteMapInfo(P(WorldFiles.MapInfo), world.MapInfo, world.Size);
        WorldXml.WritePrefabs(P(WorldFiles.Prefabs), world.Prefabs);
        WorldXml.WriteSpawns(P(WorldFiles.Spawns), world.Spawns);

        if (world.Biomes is { } biomes && !UsePassthrough(world, WorldFiles.Biomes, biomes.Indices))
            Png.WriteRows(P(WorldFiles.Biomes), biomes.Indices.Width, biomes.Indices.Height, PngPixelFormat.Rgba8,
                (y, row) => LayerImages.EncodeBiomesRow(biomes, y, row));
        else WritePassthrough(world, WorldFiles.Biomes, P(WorldFiles.Biomes));

        if (world.Roads is { } roads && !UsePassthrough(world, WorldFiles.Roads, roads))
            Png.WriteRows(P(WorldFiles.Roads), roads.Width, roads.Height, PngPixelFormat.Rgba8,
                (y, row) => LayerImages.EncodeRoadsRow(roads, y, row));
        else WritePassthrough(world, WorldFiles.Roads, P(WorldFiles.Roads));

        if (world.Water is { } water && !UsePassthrough(world, WorldFiles.Water, water))
            Png.WriteRows(P(WorldFiles.Water), water.Width, water.Height, PngPixelFormat.Rgba8,
                (y, row) => LayerImages.EncodeWaterRow(water, y, row));
        else WritePassthrough(world, WorldFiles.Water, P(WorldFiles.Water));

        if (world.Radiation is { } radiation)
            Png.WriteRows(P(WorldFiles.Radiation), radiation.Width, radiation.Height, PngPixelFormat.Rgba8,
                (y, row) => LayerImages.EncodeRadiationRow(radiation, y, row));

        foreach (var (name, bytes) in world.ExtraFiles)
            File.WriteAllBytes(P(name), bytes);

        if (!world.ExtraFiles.ContainsKey(WorldFiles.Level))
        {
            if (options.LevelTemplatePath is null)
                throw new InvalidOperationException("The world has no main.ttw; pass a template from a world generated by this game version.");
            File.Copy(options.LevelTemplatePath, P(WorldFiles.Level), overwrite: true);
        }
    }

    private static bool UsePassthrough<T>(World world, string file, Grid<T> layer) where T : unmanaged =>
        layer.Version == 0 && world.PassthroughImages.ContainsKey(file);

    private static void WritePassthrough(World world, string file, string path)
    {
        if (world.PassthroughImages.TryGetValue(file, out var image))
            Png.WriteRgba(path, image.Width, image.Height, image.Pixels);
    }
}
