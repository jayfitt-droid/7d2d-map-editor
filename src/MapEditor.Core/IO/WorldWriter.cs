using MapEditor.Core.Model;

namespace MapEditor.Core.IO;

public sealed class WorldWriteOptions
{
    /// <summary>Allow writing into a folder that already has files (derived caches are deleted).</summary>
    public bool Overwrite { get; init; }

    /// <summary>A main.ttw to use when the world has none (see <see cref="LevelFile.FindTemplate"/>).</summary>
    public byte[]? LevelTemplate { get; init; }

    /// <summary>
    /// Give main.ttw a new world GUID, and keep it in the world for later saves. Use this when saving as a
    /// new world, so the copy and the original are not the same world to the game.
    /// </summary>
    public bool NewLevelGuid { get; init; }
}

/// <summary>
/// Writes a <see cref="World"/> as a game world folder the game can load and process. Everything is written to a
/// staging folder first; only when that has all succeeded are the files swapped into the destination, with the old
/// ones kept aside and put back if the swap fails. So a failed write never leaves a mix of old and new files.
/// </summary>
public static class WorldWriter
{
    /// <summary>Sub-folders the writer uses inside the destination while it works; removed when it's done.</summary>
    public const string StagingDir = ".mapeditor-staging", BackupDir = ".mapeditor-backup";

    public static void Write(World world, string folder, WorldWriteOptions? options = null)
    {
        options ??= new WorldWriteOptions();
        folder = Path.GetFullPath(folder);

        // Check everything that can be checked before the destination is touched.
        foreach (var name in world.ExtraFiles.Keys)
            if (!WorldFiles.IsSafeExtraName(name))
                throw new InvalidOperationException($"The world has an extra file named '{name}', which can't be written into a world folder.");
        byte[] level = world.ExtraFiles.TryGetValue(WorldFiles.Level, out var existing)
            ? options.NewLevelGuid ? LevelFile.WithNewGuid(existing) : existing
            : options.LevelTemplate is { } template ? LevelFile.WithNewGuid(template)
            : throw new InvalidOperationException("The world has no main.ttw; pass a template from a world generated by this game version.");

        bool created = !Directory.Exists(folder);
        if (!created && !options.Overwrite && Directory.EnumerateFileSystemEntries(folder).Any(e => !IsOwnDir(e)))
            throw new IOException($"'{folder}' is not empty.");
        Directory.CreateDirectory(folder);

        // Leftovers from an earlier write that was cut off (the editor closed or crashed) are ours to clear.
        string stage = Path.Combine(folder, StagingDir);
        try
        {
            DeleteDir(stage);
            Directory.CreateDirectory(stage);
            Commit(folder, stage, WriteFiles(world, stage, level));
        }
        catch
        {
            TryDeleteDir(stage);
            if (created) TryDeleteDir(folder);
            throw;
        }
        TryDeleteDir(stage);
        world.ExtraFiles[WorldFiles.Level] = level;
    }

    private static bool IsOwnDir(string path) =>
        Path.GetFileName(path) is StagingDir or BackupDir && Directory.Exists(path);

    /// <summary>Writes every file of the world into <paramref name="folder"/>; returns their names.</summary>
    private static HashSet<string> WriteFiles(World world, string folder, byte[] level)
    {
        var written = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        string P(string file)
        {
            written.Add(file);
            return Path.Combine(folder, file);
        }

        HeightRaw.Write(P(WorldFiles.Height), world.Height);
        WorldXml.WriteMapInfo(P(WorldFiles.MapInfo), world.MapInfo, world.Size);
        WorldXml.WritePrefabs(P(WorldFiles.Prefabs), world.Prefabs);
        WorldXml.WriteSpawns(P(WorldFiles.Spawns), world.Spawns);

        if (Passthrough.Applies(world, WorldFiles.Biomes)) WritePassthrough(world, WorldFiles.Biomes, P);
        else if (world.Biomes is { } biomes)
            Png.WriteRows(P(WorldFiles.Biomes), biomes.Indices.Width, biomes.Indices.Height, PngPixelFormat.Rgba8,
                (y, row) => LayerImages.EncodeBiomesRow(biomes, y, row));

        if (Passthrough.Applies(world, WorldFiles.Roads)) WritePassthrough(world, WorldFiles.Roads, P);
        else if (world.Roads is { } roads)
            Png.WriteRows(P(WorldFiles.Roads), roads.Width, roads.Height, PngPixelFormat.Rgba8,
                (y, row) => LayerImages.EncodeRoadsRow(roads, y, row));

        if (Passthrough.Applies(world, WorldFiles.Water)) WritePassthrough(world, WorldFiles.Water, P);
        else if (world.Water is { } water)
            Png.WriteRows(P(WorldFiles.Water), water.Width, water.Height, PngPixelFormat.Rgba8,
                (y, row) => LayerImages.EncodeWaterRow(water, y, row));

        if (world.Radiation is { } radiation)
            Png.WriteRows(P(WorldFiles.Radiation), radiation.Width, radiation.Height, PngPixelFormat.Rgba8,
                (y, row) => LayerImages.EncodeRadiationRow(radiation, y, row));

        foreach (var (name, bytes) in world.ExtraFiles)
            if (!name.Equals(WorldFiles.Level, StringComparison.OrdinalIgnoreCase)) File.WriteAllBytes(P(name), bytes);
        File.WriteAllBytes(P(WorldFiles.Level), level);
        return written;
    }

    private static void WritePassthrough(World world, string file, Func<string, string> path)
    {
        var image = world.PassthroughImages[file];
        Png.WriteRgba(path(file), image.Width, image.Height, image.Pixels);
    }

    /// <summary>
    /// Moves the staged files into <paramref name="folder"/>. The files they replace, any layer file the world no
    /// longer has, and the game's stale caches are moved aside first and deleted at the end; if any move fails,
    /// everything is moved back as it was.
    /// </summary>
    private static void Commit(string folder, string stage, HashSet<string> written)
    {
        string backup = Path.Combine(folder, BackupDir);
        DeleteDir(backup);
        Directory.CreateDirectory(backup);
        var setAside = new List<string>();
        var placed = new List<string>();
        try
        {
            foreach (var file in Directory.GetFiles(folder))
            {
                string name = Path.GetFileName(file);
                // Stale caches would make the game skip reprocessing (it checks checksums.txt).
                if (!written.Contains(name) && !WorldFiles.Modelled.Contains(name) && !WorldFiles.IsDerived(name)) continue;
                File.Move(file, Path.Combine(backup, name));
                setAside.Add(name);
            }
            foreach (var name in written)
            {
                File.Move(Path.Combine(stage, name), Path.Combine(folder, name));
                placed.Add(name);
            }
        }
        catch
        {
            foreach (var name in placed) TryMove(Path.Combine(folder, name), Path.Combine(stage, name));
            foreach (var name in setAside) TryMove(Path.Combine(backup, name), Path.Combine(folder, name));
            TryDeleteDir(backup);
            throw;
        }
        TryDeleteDir(backup);
    }

    private static void DeleteDir(string path)
    {
        if (Directory.Exists(path)) Directory.Delete(path, recursive: true);
    }

    private static void TryDeleteDir(string path)
    {
        try
        {
            DeleteDir(path);
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
        {
            // Best effort; the next write clears it.
        }
    }

    private static void TryMove(string from, string to)
    {
        try
        {
            if (File.Exists(from)) File.Move(from, to, overwrite: true);
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
        {
            // Nothing more can be done; the rest is still put back.
        }
    }
}
